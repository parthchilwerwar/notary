/**
 * Live incident events in neatlogs. When something goes wrong while an agent works, the call site
 * reports it here and it becomes a neatlogs log() record at level warn/error, tied to the span that
 * is active at that moment (the probe, the guard, the LLM call, ...):
 *
 *   message   "incident <kind> [WARN|ERROR]: <summary>"
 *   attrs     notary.incident.id / .kind / .severity / .subject, notary.incident.spanId / .traceId
 *             (the span it happened in), notary.runId, plus small call-site facts
 *             (the SDK records each as a `log.<key>` attribute)
 *
 * Resolutions are logged the same way at level info ("incident <id> resolved: <summary>").
 *
 * The incident id is deterministic — incidentId(kind, subject, runId) — and src/incidents/derive.ts
 * uses the same function on the recorded data, so the log event in neatlogs and the row in
 * runs/<runId>/incidents.json carry the same `notary.incident.id`. The run id is part of the id: the
 * same anomaly seen by two runs (e.g. two runs started from one `notary serve`) is two incidents.
 * Live call sites take the run id from the incident run scope (enterIncidentRun / withIncidentRun,
 * set by the run pipelines) unless they pass one. Dedup is per run: at the end of a run,
 * recordRunIncidents emits every derived incident not already reported live for THAT run.
 *
 * Never throws; no-op (returns false) when tracing is off. Summaries are generated by code and pass
 * through the trace module's secret masking.
 */
import { AsyncLocalStorage } from "node:async_hooks";
import { createHash } from "node:crypto";
import type { IncidentKind, IncidentResolution, IncidentSeverity } from "../schema/incidents.js";
import { currentSpanIds, traceLogAt } from "../trace/index.js";
import type { TraceAttrs } from "../trace/index.js";

/**
 * "inc-" + sha256(runId | kind | subject)[:16]. Subjects are record keys (anomaly id, probe id, span
 * id, ...); the run id scopes them to the run the incident happened in. Without a run id (a report
 * outside any run scope) the id is sha256(kind | subject)[:16].
 */
export function incidentId(kind: IncidentKind, subject: string, runId?: string): string {
  const input = runId ? `${runId}|${kind}|${subject}` : `${kind}|${subject}`;
  return `inc-${createHash("sha256").update(input).digest("hex").slice(0, 16)}`;
}

// The run a live report belongs to: set by the run pipelines (queue run, notarize, recon).
const incidentRun = new AsyncLocalStorage<string>();

/** The run id live incident reports are attributed to here, if any. */
export function currentIncidentRun(): string | undefined {
  return incidentRun.getStore();
}

/**
 * Attribute live incident reports from here on (this async context and what it starts) to `runId`.
 * Call it only after the pipeline's first `await`, so the scope does not leak into the caller.
 */
export function enterIncidentRun(runId: string): void {
  incidentRun.enterWith(runId);
}

/** Run `fn` with live incident reports attributed to `runId` (undefined: unchanged). */
export function withIncidentRun<T>(runId: string | undefined, fn: () => T): T {
  return runId ? incidentRun.run(runId, fn) : fn();
}

// Dedup per run ("" = reports outside any run scope): run id -> incident ids sent to neatlogs.
const reported = new Map<string, Set<string>>();
const resolved = new Set<string>();

function reportedFor(runId: string | undefined): Set<string> {
  const key = runId ?? "";
  let set = reported.get(key);
  if (!set) reported.set(key, (set = new Set()));
  return set;
}

/** Incident ids already sent to neatlogs by this process for one run (default: the current run scope). */
export function reportedIncidentIds(runId: string | undefined = currentIncidentRun()): ReadonlySet<string> {
  return reportedFor(runId);
}

/** Forget what was reported (tests). */
export function resetReportedIncidents(): void {
  reported.clear();
  resolved.clear();
}

export function logLevelFor(severity: IncidentSeverity): "warn" | "error" {
  return severity === "error" ? "error" : "warn";
}

export type LiveIncident = {
  kind: IncidentKind;
  /** The record key the id is derived from (must match what derive.ts uses for this kind). */
  subject: string;
  severity: IncidentSeverity;
  summary: string;
  /** Extra facts (ids, status codes, ...). Never secrets or prompts. */
  attrs?: TraceAttrs;
  /** The span it happened in, when not the active one. */
  span?: { traceId: string; spanId: string };
  /** A precomputed id (derive.ts); default incidentId(kind, subject, runId). */
  id?: string;
  /** The run it happened in; default the current incident run scope. */
  runId?: string;
};

/** Send one incident to neatlogs as a warn/error log record. Returns its id. Idempotent per process. */
export function reportIncident(i: LiveIncident): string {
  const runId = i.runId ?? currentIncidentRun();
  const id = i.id ?? incidentId(i.kind, i.subject, runId);
  const reported = reportedFor(runId);
  if (reported.has(id)) return id;
  try {
    const span = i.span ?? currentSpanIds();
    const ok = traceLogAt(logLevelFor(i.severity), `incident ${i.kind} [${i.severity === "error" ? "ERROR" : "WARN"}]: ${i.summary}`, {
      "notary.incident.id": id,
      "notary.incident.kind": i.kind,
      "notary.incident.severity": i.severity,
      "notary.incident.subject": i.subject,
      ...(runId ? { "notary.incident.runId": runId } : {}),
      ...(span ? { "notary.incident.traceId": span.traceId, "notary.incident.spanId": span.spanId } : {}),
      ...i.attrs,
    });
    if (ok) reported.add(id);
  } catch {
    // incident reporting must never break the traced work
  }
  return id;
}

/** Log how an incident was resolved (level info). Idempotent per (id, action) per process. */
export function reportResolution(id: string, r: Pick<IncidentResolution, "status" | "action" | "summary"> & { recordIds?: string[] }): void {
  const key = `${id}|${r.action}`;
  if (resolved.has(key)) return;
  try {
    const ok = traceLogAt("info", `incident ${id} ${r.status === "resolved" ? "resolved" : r.status.replace("_", " ")}: ${r.summary}`, {
      "notary.incident.id": id,
      "notary.incident.resolution": r.status,
      "notary.incident.resolution.action": r.action,
      ...(r.recordIds?.length ? { "notary.incident.resolution.records": r.recordIds.join(",") } : {}),
    });
    if (ok) resolved.add(key);
  } catch {
    // never break the traced work
  }
}
