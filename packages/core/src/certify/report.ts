/**
 * Certificate report: per-tool counts and a human-readable REPORT.md, computed from a CertificateSet
 * (which is computed from verified bundles). No hand-typed numbers and no clock: rerunning the export
 * on the same bundles produces byte-identical files.
 *
 * Counts (per tool, and overall = the sum):
 *   claimsTotal      claims the export covers (contract claims + any claim a source bundle carries)
 *   certified        claims with an ACTIVE certificate (= matchesDocs + contradictsDocs)
 *   matchesDocs      active certificates whose verdict is "matches docs"
 *   contradictsDocs  active certificates whose verdict is "contradicts docs: …"
 *   unproven         claims without an active certificate (= claimsTotal − certified; includes claims
 *                    whose only certificate was revoked)
 *   revoked          certificates revoked (a belief left `notarized` after it was issued)
 *
 * Browser-safe module.
 */
import { z } from "zod";
import { Sha256HexSchema, ToolSchema } from "../schema/common.js";
import type { CertificateSet, ToolCertificates } from "./certificates.js";
import { SourceBundleSchema } from "./certificates.js";

export const ReportCountsSchema = z
  .object({
    claimsTotal: z.number().int().nonnegative(),
    certified: z.number().int().nonnegative(),
    matchesDocs: z.number().int().nonnegative(),
    contradictsDocs: z.number().int().nonnegative(),
    unproven: z.number().int().nonnegative(),
    revoked: z.number().int().nonnegative(),
  })
  .strict();

export const CertificateReportSchema = z
  .object({
    generatedBy: z.string(),
    sample: z.boolean(),
    /** Fixture scenario (one simulated world), absent for real data. */
    scenario: z.string().optional(),
    disclosure: z.array(z.string()),
    header: z.string(),
    sourceBundles: z.array(SourceBundleSchema),
    tools: z.array(z.object({ tool: ToolSchema, header: z.string(), counts: ReportCountsSchema, file: z.string() }).strict()),
    overall: ReportCountsSchema,
    /** sha256 of each per-tool file's canonical JSON, so the report pins exactly what it counted. */
    toolFileHashes: z.record(z.string(), Sha256HexSchema),
  })
  .strict();

export type ReportCounts = z.infer<typeof ReportCountsSchema>;
export type CertificateReport = z.infer<typeof CertificateReportSchema>;

export function countsFor(t: ToolCertificates): ReportCounts {
  const active = t.certificates.filter((c) => c.status === "active");
  const claimsTotal = new Set([...t.certificates.map((c) => c.claimId), ...t.noCertificates.map((n) => n.claimId)]).size;
  const certified = new Set(active.map((c) => c.claimId)).size;
  return {
    claimsTotal,
    certified,
    matchesDocs: active.filter((c) => c.verdictKind === "matches_docs").length,
    contradictsDocs: active.filter((c) => c.verdictKind === "contradicts_docs").length,
    unproven: claimsTotal - certified,
    revoked: t.certificates.filter((c) => c.status === "revoked").length,
  };
}

function sum(all: readonly ReportCounts[]): ReportCounts {
  const zero: ReportCounts = { claimsTotal: 0, certified: 0, matchesDocs: 0, contradictsDocs: 0, unproven: 0, revoked: 0 };
  return all.reduce(
    (a, c) => ({
      claimsTotal: a.claimsTotal + c.claimsTotal,
      certified: a.certified + c.certified,
      matchesDocs: a.matchesDocs + c.matchesDocs,
      contradictsDocs: a.contradictsDocs + c.contradictsDocs,
      unproven: a.unproven + c.unproven,
      revoked: a.revoked + c.revoked,
    }),
    zero,
  );
}

export function buildReport(set: CertificateSet, fileHashes: Record<string, string>, fileFor: (tool: string) => string): CertificateReport {
  const seen = new Map<string, z.infer<typeof SourceBundleSchema>>();
  for (const t of set.tools) for (const s of t.sourceBundles) seen.set(s.runId, s);
  const sourceBundles = [...seen.values()].sort((a, b) => Date.parse(a.startedAt) - Date.parse(b.startedAt) || (a.runId < b.runId ? -1 : 1));
  const tools = set.tools.map((t) => ({ tool: t.tool, header: t.header, counts: countsFor(t), file: fileFor(t.tool) }));
  const scen = set.scenario ? ` Scenario ${set.scenario}.` : "";
  const header = sourceBundles.length
    ? `${set.sample ? `FIXTURE — simulated APIs and models, not a live run.${scen} ` : ""}Generated by \`${set.generatedBy}\` from ${sourceBundles.length} hash-verified ${set.sample ? "fixture" : "real"} bundle(s); no hand-typed numbers.`
    : `${set.sample ? `FIXTURE — no fixture bundles found.${scen} Every` : "No real runs yet: every"} claim is not tested and every count is zero. Generated by \`${set.generatedBy}\`.`;
  return CertificateReportSchema.parse({
    generatedBy: set.generatedBy,
    sample: set.sample,
    ...(set.scenario ? { scenario: set.scenario } : {}),
    disclosure: set.disclosure,
    header,
    sourceBundles,
    tools,
    overall: sum(tools.map((t) => t.counts)),
    toolFileHashes: fileHashes,
  });
}

const TOOL_TITLE: Record<string, string> = { crustdata: "Crustdata", dodo: "Dodo Payments (test mode)" };

function cell(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

/** export/REPORT.md (or REPORT.fixture.md): tables per tool, every certificate's verdict line, revocations. */
export function renderReportMd(report: CertificateReport, set: CertificateSet, opts: { shift?: number } = {}): string {
  const title = set.sample
    ? `# Notary certificates — FIXTURE${set.scenario ? ` scenario ${set.scenario}` : ""} (simulated, not a live run)`
    : "# Notary certificates";
  const out: string[] = [title, ""];
  out.push(`> ${report.header}`, `> Do not edit by hand: rerun \`${report.generatedBy}\`.`, "");
  if (set.sample) out.push(`**${set.disclosure.join(" ")}** Nothing in this file is a claim about the real APIs.`, "");
  out.push("## Source bundles", "");
  if (report.sourceBundles.length === 0) out.push(set.sample ? "None: no fixture bundles found (run `pnpm notary demo --fixture`)." : "None: no real runs yet (run `pnpm notary notarize --tool <crustdata|dodo>`, then re-export).");
  for (const s of report.sourceBundles) out.push(`- \`${s.runId}\` (${s.kind}, ${s.mode}, started ${s.startedAt}) — contentHash \`${s.contentHash}\``);
  out.push("");
  out.push("## Summary", "", "| Tool | Claims | Certified | Matches docs | Contradicts docs | Unproven | Revoked |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const t of report.tools) {
    const c = t.counts;
    out.push(`| ${TOOL_TITLE[t.tool] ?? t.tool} | ${c.claimsTotal} | ${c.certified} | ${c.matchesDocs} | ${c.contradictsDocs} | ${c.unproven} | ${c.revoked} |`);
  }
  const o = report.overall;
  out.push(`| **All** | ${o.claimsTotal} | ${o.certified} | ${o.matchesDocs} | ${o.contradictsDocs} | ${o.unproven} | ${o.revoked} |`, "");
  out.push(
    "Certified = claims with an active certificate. Unproven = claims without one (including claims whose certificate was revoked). Revoked counts certificates.",
    "",
  );

  for (const t of set.tools) {
    out.push(`## ${TOOL_TITLE[t.tool] ?? t.tool}`, "", `_${t.header}_`, "");
    out.push("### Certificates", "");
    if (t.certificates.length === 0) out.push("None.", "");
    for (const c of t.certificates) {
      out.push(`- **\`${c.claimId}\`** — ${c.status === "revoked" ? `~~${cell(c.verdict)}~~ **REVOKED** (${c.revocation?.id} at ${c.revocation?.revokedAt})` : cell(c.verdict)}`);
      out.push(`  - Doc: "${cell(c.docText)}" — [source](${c.docUrl})`);
      out.push(`  - Scope: ${cell(c.scope.text)}`);
      out.push(`  - Issued ${c.issuedAt}${c.issuedFrom === "snapshot" ? " (from the belief snapshot; the notarization event is not in a source bundle)" : ""} · confidence ${c.confidence} (α/β = ${c.alpha}/${c.beta}) · adversary ${c.adversary ? `${c.adversary.verdict} (${c.adversary.backend ?? "unrecorded"}, \`${c.adversary.model}\`)` : "not recorded"}`);
      out.push(`  - Evidence: ${c.evidence.map((e) => `\`${e.probeId}\` → trace \`${e.traceId}\``).join("; ") || "none"}`);
      out.push(`  - \`${c.id}\` · sha256 \`${c.sha256}\` · from \`${c.sourceBundle.runId}\``);
    }
    if (t.certificates.length) out.push("");
    out.push("### Revocations", "");
    if (t.revocations.length === 0) out.push("None.", "");
    for (const r of t.revocations) {
      out.push(`- **\`${r.claimId}\`**: certificate \`${r.certificateId}\` revoked at ${r.revokedAt} (notarized → ${r.to}) — ${cell(r.reason)}`);
      out.push(`  - Triggered by: ${r.triggerProbeIds.map((p) => `\`${p}\``).join(", ") || "no probe recorded"}${r.triggerTraceIds.length ? ` (traces ${r.triggerTraceIds.map((x) => `\`${x}\``).join(", ")})` : ""}`);
      out.push(`  - Guards retired: ${r.guardsRetired.map((g) => `\`${g.id}\` (${g.kind} on \`${g.operation}\`, ${g.retiredAt})`).join(", ") || "none recorded in the source bundles"}`);
    }
    if (t.revocations.length) out.push("");
    out.push("### No certificate", "", "| Claim | Status | Reason |", "| --- | --- | --- |");
    for (const n of t.noCertificates) out.push(`| \`${n.claimId}\` | ${n.status} | ${cell(n.reason)} |`);
    out.push("");
  }
  const shift = "#".repeat(opts.shift ?? 0);
  const text = shift ? out.map((l) => (/^#+ /.test(l) ? `${shift}${l}` : l)) : out;
  return `${text.join("\n").trimEnd()}\n`;
}

/** packages/web/public/certificates/fixture/index.json: the fixture scenarios (separate simulated worlds). */
export const FixtureIndexSchema = z
  .object({
    generatedBy: z.string(),
    sample: z.literal(true),
    disclosure: z.array(z.string()),
    note: z.string(),
    scenarios: z.array(
      z
        .object({
          scenario: z.string(),
          report: z.string(),
          files: z.array(z.string()),
          sourceBundles: z.array(z.string()),
          overall: ReportCountsSchema,
        })
        .strict(),
    ),
  })
  .strict();

export type FixtureIndex = z.infer<typeof FixtureIndexSchema>;
