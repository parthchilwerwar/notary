/**
 * export/TOOLS.md (PRD FR-19): the corrected tool spec. Per tool, per documented claim: the doc text
 * and link, then what Notary verified, read from the newest full notarize bundle for that tool.
 * Only a `notarized` belief counts as verified; every other claim says so explicitly. With no real
 * notarize bundle the file still lists every claim (the doc claims Notary will test), all unverified.
 */
import { allContracts } from "../contracts/index.js";
import type { Belief, Claim, Guard, RunBundle, Tool } from "../schema/index.js";
import { latestNotarize } from "./collect.js";
import { commandFor } from "./commands.js";

export const UNVERIFIED = "Unverified — no notarized evidence";

const TOOLS: readonly Tool[] = ["crustdata", "dodo"];

const TOOL_TITLE: Record<Tool, string> = { crustdata: "Crustdata", dodo: "Dodo Payments (test mode)" };

/** Contract claims first (in contract order), then any claim a bundle carries that the contract lacks. */
function claimsFor(tool: Tool, source: RunBundle | undefined): Claim[] {
  const out = allContracts.map((e) => e.claim).filter((c) => c.tool === tool);
  const seen = new Set(out.map((c) => c.id));
  for (const c of source?.claims ?? []) if (c.tool === tool && !seen.has(c.id)) out.push(c);
  return out;
}

function quote(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

function beliefLines(b: Belief): string[] {
  const lines = [
    `  - Belief \`${b.id}\`: status **${b.status}**, confidence ${b.confidence} (P(doc claim holds)), α/β = ${b.alpha}/${b.beta}, defect class ${b.class ? `\`${b.class}\`` : "none recorded"}`,
    `  - Statement: ${quote(b.statement)}`,
  ];
  if (b.prior) lines.push(`  - Started from transfer prior Beta(${b.prior.alpha}, ${b.prior.beta}) learned on ${b.prior.from}`);
  if (b.adversary) {
    const a = b.adversary;
    lines.push(
      `  - Adversary: **${a.verdict}**${a.scope ? `, scope: ${quote(a.scope)}` : ""} (backend ${a.backend ?? "unrecorded"}, model \`${a.model}\`) — ${quote(a.reason)}`,
    );
  } else {
    lines.push("  - Adversary: not reviewed");
  }
  if (b.evidence.length) {
    const ev = b.evidence.map((e) => `\`${e.probeId}\` (trace \`${e.traceId}\`${e.valid === false ? ", INVALID" : e.valid === true ? ", valid" : ""})`);
    lines.push(`  - Evidence (probe → trace): ${ev.join("; ")}`);
  } else {
    lines.push("  - Evidence: none cited");
  }
  return lines;
}

function guardLines(guards: Guard[]): string[] {
  const active = guards.filter((g) => g.active);
  const retired = guards.filter((g) => !g.active);
  const lines: string[] = [];
  if (active.length === 0) lines.push("  - Active guard: none");
  for (const g of active) lines.push(`  - Active guard: \`${g.id}\` — ${g.kind} on \`${g.operation}\` (${g.class}): ${quote(g.reason)}`);
  for (const g of retired) lines.push(`  - Retired guard: \`${g.id}\` — ${g.kind} on \`${g.operation}\`${g.retiredAt ? `, retired ${g.retiredAt}` : ""}`);
  return lines;
}

function verdictLine(b: Belief | undefined): string {
  if (!b || b.status !== "notarized") return `**${UNVERIFIED}.**`;
  const side = b.statement.startsWith("Doc claim violated") ? `the doc is WRONG here (${b.class ?? "violated"})` : "the doc claim holds";
  return `**Notarized: ${side}.**`;
}

export function renderToolsMd(opts: { bundles: readonly RunBundle[]; generatedAt: string }): string {
  const sources = TOOLS.map((t) => [t, latestNotarize(opts.bundles, t)] as const);
  const used = sources.filter(([, b]) => b !== undefined) as [Tool, RunBundle][];
  const out: string[] = [
    "# Corrected tool spec",
    "",
    `> Generated by \`pnpm notary export\` at ${opts.generatedAt} — do not edit by hand.`,
    "",
  ];
  if (used.length === 0) {
    out.push(
      "**No real notarize bundles exist yet**, so every claim below is listed as unverified. This file is still the list of",
      "documented claims Notary will test; run `pnpm notary notarize --tool <crustdata|dodo>` and re-export to fill it in.",
      "",
    );
  } else {
    out.push("Source bundles (newest full notarize bundle per tool, hash-verified):", "");
    for (const [tool, b] of used) out.push(`- ${tool}: \`${b.runId}\` (contentHash \`${b.contentHash}\`), produced by \`${commandFor(b)}\``);
    for (const [tool, b] of sources) if (!b) out.push(`- ${tool}: no notarize bundle — every ${tool} claim is unverified`);
    out.push("");
  }
  out.push(
    "Only a **notarized** belief (survived the adversary) counts as verified. Confidence is P(doc claim holds) under Beta(α, β).",
    "Claims whose belief is still a hypothesis, candidate, abstained, refuted or unlearned are marked unverified, with Notary's latest state shown.",
    "",
  );

  for (const [tool, source] of sources) {
    out.push(`## ${TOOL_TITLE[tool]}`, "");
    const claims = claimsFor(tool, source);
    const beliefs = new Map<string, Belief>((source?.beliefs.after ?? []).filter((b) => b.tool === tool).map((b) => [b.claimId, b]));
    const guards = source?.guards ?? [];
    for (const c of claims) {
      const belief = beliefs.get(c.id);
      out.push(`### \`${c.id}\``, "");
      out.push(`- Operation: \`${c.operation}\`${c.endpoint ? ` (\`${c.endpoint}\`)` : ""}${c.param ? `, param \`${c.param}\`` : ""}`);
      out.push(`- Doc says: "${quote(c.docText)}" — [source](${c.docUrl})`);
      out.push(`- Checked as: \`${JSON.stringify(c.expect)}\``);
      out.push(`- Notary: ${verdictLine(belief)}`);
      if (belief) {
        if (belief.status !== "notarized") out.push("  - Latest state (not notarized, not a verified result):");
        out.push(...beliefLines(belief));
        out.push(...guardLines(guards.filter((g) => g.beliefId === belief.id)));
      } else if (source) {
        out.push("  - No belief recorded for this claim in the source bundle.");
      }
      out.push("");
    }
  }
  return `${out.join("\n").trimEnd()}\n`;
}
