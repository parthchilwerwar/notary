// v2 timeline: runs/<runId>/timeline.jsonl, one TimelineEvent per line, ordered by `seq`.
// Published next to each bundle as <runId>.timeline.json (a TimelineFile). Browser-safe: zod only.
// The run bundle schema is frozen; the timeline is a separate, derived record of what happened.
import { z } from "zod";
import { RoleSchema } from "./common.js";

// Read → Test → Challenge → Certify → Enforce (README "How it works").
export const TimelineStageSchema = z.enum(["read", "test", "challenge", "certify", "enforce"]);

// The first eight are the v2 spec's list; anomaly.detected, adversary.verdict and
// approval.decided give the Read and Challenge stages and the approval desk their own events
// (DECISIONS: v2 timeline event types).
export const TimelineEventTypeSchema = z.enum([
  "anomaly.detected",
  "decision",
  "probe.committed",
  "probe.verdict",
  "adversary.verdict",
  "belief.changed",
  "certificate.issued",
  "certificate.revoked",
  "budget",
  "approval.decided",
  "run.finished",
]);

export const BudgetMeterSchema = z.object({
  used: z.number().nonnegative(),
  // null = no cap configured for this meter.
  cap: z.number().nonnegative().nullable(),
});

// Snapshot carried by `budget` events (and repeated in run.finished.data.budget).
export const BudgetSnapshotSchema = z.object({
  credits: BudgetMeterSchema,
  toolCalls: BudgetMeterSchema,
  usdByRole: z.record(RoleSchema, z.number().nonnegative()),
  usdCap: z.number().nonnegative().nullable(),
  // Set when a cap stopped the run (the bundle's stopReason).
  stopReason: z.string().optional(),
});

export const TimelineEventSchema = z.object({
  runId: z.string(),
  // 0-based, strictly increasing within a run; the order events happened in.
  seq: z.number().int().nonnegative(),
  at: z.iso.datetime(),
  stage: TimelineStageSchema,
  type: TimelineEventTypeSchema,
  // Ids of bundle records (decision, probe, hypothesis, belief, claim, anomaly), certificate or
  // revocation ids, or approval ids this event is about. First id is the primary record.
  recordIds: z.array(z.string()),
  // neatlogs / local span trace ids ("" never appears; omitted when tracing was off).
  traceIds: z.array(z.string()),
  // One plain sentence generated by code from the records (never by a model).
  summary: z.string(),
  // Small structured facts for the UI, e.g. { status: "held" } or a BudgetSnapshot under "budget".
  data: z.record(z.string(), z.unknown()).optional(),
});

// Published form: packages/web/public/bundles/**/<runId>.timeline.json
export const TimelineFileSchema = z.object({
  runId: z.string(),
  sample: z.boolean(),
  // contentHash of the bundle this timeline belongs to (ties the two together).
  bundleHash: z.string().regex(/^[0-9a-f]{64}$/),
  events: z.array(TimelineEventSchema),
});

export type TimelineStage = z.infer<typeof TimelineStageSchema>;
export type TimelineEventType = z.infer<typeof TimelineEventTypeSchema>;
export type BudgetMeter = z.infer<typeof BudgetMeterSchema>;
export type BudgetSnapshot = z.infer<typeof BudgetSnapshotSchema>;
export type TimelineEvent = z.infer<typeof TimelineEventSchema>;
export type TimelineFile = z.infer<typeof TimelineFileSchema>;
