// Incidents: the things that went wrong (or nearly did) while Notary's agents worked, each tied to
// the neatlogs span where it happened and to how it was resolved. Browser-safe: zod only.
//
// Written per run to runs/<runId>/incidents.json (an IncidentsFile) by src/incidents/record.ts and
// published by `notary export` / `pnpm --filter @notary/core publish:incidents` as
// packages/web/public/incidents/<runId>.json plus the aggregate packages/web/public/incidents/index.json
// (an IncidentsIndex); fixture runs under packages/web/public/incidents/fixture/. Never inside
// public/bundles (its loaders treat every JSON there as a bundle or timeline).
//
// Every incident is DERIVED BY CODE from recorded data (the run bundle, its timeline, approvals and
// runs/<runId>/spans.jsonl) — never by a model. The run bundle schema stays frozen; this is a
// separate, derived record.
import { z } from "zod";
import { AgentIdSchema } from "./agents.js";

export const IncidentKindSchema = z.enum([
  // The deterministic checker saw a response that contradicts the documentation.
  "checker_anomaly",
  // A probe's committed prediction for a documented behavior lost: reality contradicts the docs.
  "probe_contradiction",
  // A notarized belief lost its certificate (drift): the API changed under us.
  "belief_unlearned",
  // The Adversary downgraded (or narrowed) a belief the Reflector wanted certified.
  "adversary_downgrade",
  // The Guard held a money action because a required belief is not notarized.
  "guard_hold",
  // A compiled guard refused a call outright (block / failed precheck / unprovable scope).
  "guard_block",
  // A compiled guard rewrote or refused a call that would have been a duplicate or wrong-unit action.
  "unsafe_action_prevented",
  // The deterministic grader found an executed money action unsafe (duplicate, wrong unit, missed
  // existing refund) — typically the unguarded (naive) variant.
  "unsafe_action_executed",
  // A credit / tool-call / USD budget stopped the run.
  "budget_stop",
  // A provider answered 429 and the call was retried after a back-off.
  "rate_limited",
  // A model call failed (after any retries).
  "model_error",
  // A tool (Crustdata / Dodo) call failed without an answer, or a probe could not complete.
  "tool_error",
]);

// warning -> neatlogs log level "warn", error -> "error".
export const IncidentSeveritySchema = z.enum(["warning", "error"]);

export const IncidentResolutionStatusSchema = z.enum([
  // Fixed by the system: a guard compiled, a retry succeeded, the action was refused safely, ...
  "resolved",
  // Contained but needs a person (a held action waiting for approval).
  "awaiting_human",
  // Nothing has resolved it yet.
  "open",
]);

export const IncidentResolutionActionSchema = z.enum([
  "guard_compiled", // a guard was compiled from the belief that explains the incident
  "certified", // the corrected behavior was notarized (certificate issued)
  "belief_refuted", // the doc claim was refuted and recorded as such (TOOLS.md correction)
  "belief_abstained", // Notary declined to certify: not enough evidence (kept out of guards)
  "guard_retired", // the guard of an unlearned belief was retired
  "recertified", // an unlearned belief was notarized again later
  "held_for_person", // the action was held with an evidence pack for a human
  "approved", // a person approved the held action
  "rejected", // a person rejected the held action
  "action_refused", // the guard refused the call; no money moved
  "action_rewritten", // the guard rewrote the call (e.g. units) before it left the process
  "retried", // the provider call succeeded after a back-off
  "run_stopped", // the run stopped cleanly at the cap
  "failed_safe", // the caller took its fail-safe path (no unsafe action)
  "none",
]);

export const IncidentResolutionSchema = z.object({
  status: IncidentResolutionStatusSchema,
  action: IncidentResolutionActionSchema,
  // One plain sentence generated by code from the records.
  summary: z.string(),
  at: z.iso.datetime().optional(),
  // Records the resolution points at: guard id, certificate/belief id, approval id, ...
  recordIds: z.array(z.string()),
});

const HexTraceId = z.string().regex(/^[0-9a-f]{32}$/);
const HexSpanId = z.string().regex(/^[0-9a-f]{16}$/);

export const IncidentSchema = z.object({
  // "inc-" + sha256(kind | subject)[:16]; the same id is stamped on the neatlogs log event
  // (attribute notary.incident.id), so the two can be matched.
  id: z.string().regex(/^inc-[0-9a-f]{16}$/),
  runId: z.string(),
  kind: IncidentKindSchema,
  severity: IncidentSeveritySchema,
  // When it happened (best timestamp in the records; the run start when none is finer).
  at: z.iso.datetime(),
  // Which agent (or deterministic rule) was working when it happened; absent for the checker/budget.
  agent: AgentIdSchema.optional(),
  tool: z.enum(["crustdata", "dodo"]).optional(),
  // One plain sentence generated by code from the records (never by a model).
  summary: z.string(),
  // Bundle record ids this is about (anomaly, probe, belief, decision, guard, claim), first = primary.
  recordIds: z.array(z.string()),
  claimId: z.string().optional(),
  beliefId: z.string().optional(),
  decisionId: z.string().optional(),
  // The neatlogs span where it happened (absent when tracing was off for that step).
  traceId: HexTraceId.optional(),
  spanId: HexSpanId.optional(),
  // true only when that span was actually exported to neatlogs (spans.jsonl `exported: true`).
  exported: z.boolean(),
  // neatlogs URL of the trace: only from a template derived from a real trace URL
  // (`notary trace-link`); otherwise absent and the UI shows the trace id.
  traceUrl: z.url().optional(),
  resolution: IncidentResolutionSchema,
  // Small structured facts for the UI (status codes, guard kind, attempts, ...).
  data: z.record(z.string(), z.union([z.string(), z.number(), z.boolean(), z.null()])).optional(),
});

// runs/<runId>/incidents.json and the published public/incidents[/fixture]/<runId>.json.
export const IncidentsFileSchema = z.object({
  runId: z.string(),
  sample: z.boolean(),
  // contentHash of the bundle these incidents were derived from.
  bundleHash: z.string().regex(/^[0-9a-f]{64}$/),
  // The data the derivation read, e.g. ["bundle", "timeline", "spans", "approvals"].
  sources: z.array(z.enum(["bundle", "timeline", "spans", "approvals"])),
  incidents: z.array(IncidentSchema),
});

// packages/web/public/incidents[/fixture]/index.json: every published run's incidents, newest first.
// contentHash = sha256(canonicalJson(the file without contentHash)), as for bundles (src/bundle/hash.ts),
// so the browser can verify the published file; optional only so older files still parse.
export const IncidentsIndexSchema = z.object({
  sample: z.boolean(),
  runs: z.array(IncidentsFileSchema),
  contentHash: z.string().regex(/^[0-9a-f]{64}$/).optional(),
});

export type IncidentKind = z.infer<typeof IncidentKindSchema>;
export type IncidentSeverity = z.infer<typeof IncidentSeveritySchema>;
export type IncidentResolutionStatus = z.infer<typeof IncidentResolutionStatusSchema>;
export type IncidentResolutionAction = z.infer<typeof IncidentResolutionActionSchema>;
export type IncidentResolution = z.infer<typeof IncidentResolutionSchema>;
export type Incident = z.infer<typeof IncidentSchema>;
export type IncidentsFile = z.infer<typeof IncidentsFileSchema>;
export type IncidentsIndex = z.infer<typeof IncidentsIndexSchema>;
