// The three required hackathon tools, with status, purpose, notes and links exactly as
// `notary export --evidence` wrote them to public/evidence/evidence.json.
import { Link } from "react-router";
import { Card, StatusPill } from "../ui";
import { safeLink } from "../../data";
import { REQUIRED_TOOLS } from "../../landing-data";
import type { EvidenceEntry } from "../../state/DataProvider";

export function RequiredTools({
  tools,
  error,
  loading,
}: {
  tools: EvidenceEntry[];
  error: string;
  loading: boolean;
}) {
  return (
    <section
      id="required-tools"
      className="landing-section"
      aria-labelledby="tools-title"
    >
      <div className="chapter-heading">
        <span className="eyebrow">Required tools</span>
        <h2 id="tools-title">Three tools. Status straight from the evidence file.</h2>
        <p>
          Generated by <code>pnpm notary export --evidence</code> from facts on
          disk. A tool is live only when its evidence exists.
        </p>
      </div>
      {error && (
        <p role="alert" className="landing-data-error">
          {error} Tool status is unknown, not assumed.
        </p>
      )}
      <div className="landing-tools">
        {REQUIRED_TOOLS.map((name) => {
          const tool = tools.find(
            (t) => t.name.toLowerCase() === name.toLowerCase(),
          );
          const links = (tool?.links ?? []).filter((l) => safeLink(l.url));
          return (
            <Card className="landing-tool" key={name}>
              <div className="tool-title">
                <h3>{name}</h3>
                {tool ? (
                  <StatusPill value={tool.status} />
                ) : (
                  <StatusPill tone="neutral">
                    {loading ? "loading" : "not in evidence file"}
                  </StatusPill>
                )}
              </div>
              <p>{tool?.purpose ?? "No entry in public/evidence/evidence.json."}</p>
              {tool?.notes && (
                <details className="record-details">
                  <summary>Evidence and limitations</summary>
                  <p>{tool.notes}</p>
                </details>
              )}
              <div className="tool-links">
                {links.map((link) => (
                  <a
                    key={link.url}
                    href={safeLink(link.url)}
                    target="_blank"
                    rel="noreferrer"
                  >
                    {link.label} ↗
                  </a>
                ))}
                {tool && links.length === 0 && (
                  <span className="muted">No public evidence link yet.</span>
                )}
              </div>
            </Card>
          );
        })}
      </div>
      <p className="chart-note">
        Full receipts: <Link to="/app/evidence">Evidence page</Link> ·{" "}
        <a
          href={`${import.meta.env.BASE_URL}evidence/evidence.json`}
          target="_blank"
          rel="noreferrer"
        >
          evidence.json
        </a>
      </p>
    </section>
  );
}
