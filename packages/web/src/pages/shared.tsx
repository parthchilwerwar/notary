// Helpers every page uses: the selected bundle, run-preserving links, record lookups and
// the certificate world gate.
import type { ReactNode } from "react";
import { Link, useLocation } from "react-router";
import type { RunBundle } from "../../../core/src/schema";
import { useData } from "../state/DataProvider";
import { withRun } from "../state/data-mode";
import type { CertificateView as CertificateWorld } from "../data";
import {
  EmptyState,
  ErrorState,
  LoadingState,
} from "../components/ui/states";
import { Button } from "../components/ui/button";

/** The selected, hash-verified bundle. The shell only renders pages once it exists. */
export function useBundle(): RunBundle {
  const { bundle } = useData();
  if (!bundle) throw new Error("No selected bundle; the shell gates pages on it.");
  return bundle;
}

/** `/app/...` path that keeps the selected run in the query string. */
export function useRunPath() {
  const { selectedRunId } = useData();
  return (path: string, extra?: Record<string, string | undefined>) =>
    withRun(path, selectedRunId, extra);
}

export function RunLink({
  to,
  children,
  className,
}: {
  to: string;
  children: ReactNode;
  className?: string;
}) {
  const path = useRunPath();
  return (
    <Link className={className} to={path(to)}>
      {children}
    </Link>
  );
}

/**
 * A record id that is not in the selected run. Lists the runs (same cohort first) that do
 * contain it, each as a shareable link.
 */
export function RecordNotFound({
  kind,
  id,
  listPath,
  find,
}: {
  kind: string;
  id: string;
  listPath: string;
  find: (b: RunBundle) => boolean;
}) {
  const { bundles, bundle } = useData();
  const { pathname } = useLocation();
  const path = useRunPath();
  const elsewhere = bundles
    .filter((b) => find(b))
    .sort((a, b) => Number(a.sample !== bundle?.sample) - Number(b.sample !== bundle?.sample));
  return (
    <EmptyState
      title={`${kind} ${id} is not in this run`}
      actions={
        <>
          {elsewhere.map((b) => (
            <Button variant="outline" asChild key={b.runId}>
              <Link to={withRun(pathname, b.runId)}>
                Open in {b.runId}
                {b.sample ? " (fixture)" : ""}
              </Link>
            </Button>
          ))}
          <Button asChild>
            <Link to={path(listPath)}>Back to the list</Link>
          </Button>
        </>
      }
    >
      {elsewhere.length
        ? `The selected run ${bundle?.runId ?? ""} has no ${kind.toLowerCase()} with this id. It is recorded in the runs below.`
        : `No published run has a ${kind.toLowerCase()} with this id.`}
    </EmptyState>
  );
}

/** Renders children with the selected run's certificate world, or the right state card. */
export function WithCertificates({
  children,
}: {
  children: (world: CertificateWorld) => ReactNode;
}) {
  const { certificates, bundle } = useData();
  if (certificates.status === "loading")
    return (
      <LoadingState title="Verifying certificate seals…">
        Checking the shared certificate schema and recomputing every seal.
      </LoadingState>
    );
  if (certificates.status === "error")
    return (
      <ErrorState title="Certificates withheld">{certificates.error}</ErrorState>
    );
  if (certificates.status === "missing")
    return (
      <EmptyState title="No certificate export published">
        {bundle?.sample
          ? "No fixture certificate export is published for this simulated world."
          : "No certificate export is published for recorded runs."}{" "}
        Certificates are generated by <code>pnpm notary export --certificates</code>.
      </EmptyState>
    );
  return <>{children(certificates.data)}</>;
}
